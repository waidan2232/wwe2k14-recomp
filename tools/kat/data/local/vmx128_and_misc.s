test_cr_logic:
  li r3, 5
  cmpwi r3, 5
  cror 4, 2, 2
  crorc 5, 0, 0
  crxor 2, 2, 2
  mcrf cr7, cr1
  mfcr r12
  blr
  #_ REGISTER_OUT r12 0x0C00000C

