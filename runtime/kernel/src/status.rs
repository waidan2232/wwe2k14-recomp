/// `RtlNtStatusToDosError` for the statuses this kernel produces.
pub fn to_dos_error(status: u32) -> u32 {
    match status {
        STATUS_SUCCESS => ERROR_SUCCESS,
        STATUS_PENDING => ERROR_IO_PENDING,
        STATUS_TIMEOUT => 0x5B4, // ERROR_TIMEOUT
        STATUS_BUFFER_OVERFLOW => 234, // ERROR_MORE_DATA
        STATUS_NO_MORE_FILES | STATUS_NO_SUCH_FILE => ERROR_NO_MORE_FILES,
        STATUS_INVALID_HANDLE | STATUS_OBJECT_TYPE_MISMATCH => ERROR_INVALID_HANDLE,
        STATUS_INVALID_PARAMETER | STATUS_INVALID_INFO_CLASS | STATUS_INFO_LENGTH_MISMATCH => ERROR_INVALID_PARAMETER,
        STATUS_END_OF_FILE => 38, // ERROR_HANDLE_EOF
        STATUS_NO_MEMORY => ERROR_NOT_ENOUGH_MEMORY,
        STATUS_ACCESS_DENIED | STATUS_MEDIA_WRITE_PROTECTED => ERROR_ACCESS_DENIED,
        STATUS_BUFFER_TOO_SMALL => ERROR_INSUFFICIENT_BUFFER,
        STATUS_OBJECT_NAME_INVALID => 123, // ERROR_INVALID_NAME
        STATUS_OBJECT_NAME_NOT_FOUND => ERROR_FILE_NOT_FOUND,
        STATUS_OBJECT_NAME_COLLISION => ERROR_ALREADY_EXISTS,
        STATUS_OBJECT_PATH_NOT_FOUND => ERROR_PATH_NOT_FOUND,
        STATUS_NOT_IMPLEMENTED | STATUS_NOT_SUPPORTED => ERROR_NOT_SUPPORTED,
        STATUS_FILE_IS_A_DIRECTORY => ERROR_ACCESS_DENIED,
        STATUS_DIRECTORY_NOT_EMPTY => 145,
        STATUS_NOT_A_DIRECTORY => 267, // ERROR_DIRECTORY
        STATUS_CANCELLED => 995,      // ERROR_OPERATION_ABORTED
        STATUS_NOT_FOUND => ERROR_NOT_FOUND,
        STATUS_DISK_FULL => 112,
        STATUS_SEMAPHORE_LIMIT_EXCEEDED => 298, // ERROR_TOO_MANY_POSTS
        STATUS_MUTANT_NOT_OWNED => 288,        // ERROR_NOT_OWNER
        _ => ERROR_FUNCTION_FAILED,
    }
}
